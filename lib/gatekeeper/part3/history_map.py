"""PART 3 (new): where and how does the mouse brain hold the recent past?

Motivation
  * Our Oct 22 result: brain-wide "prior" signals cannot be told apart from the last ~3 trials. So the brain-wide
    variable is recent HISTORY, not a long-horizon prior.
  * Nature 2026 (zebrafish, Mu & Wu labs): a thalamic ATTRACTOR holds the most recent stimulus side as a discrete
    state, and a brainstem INTEGRATOR combines several recent experiences and drives history-biased choices.
    Nobody has tested whether the mammalian brain uses the same architecture. The IBL data can.
  * Slow drift is the main trap: drift correlates with ANY slowly varying label, so a naive analysis finds
    "memory" that lasts many trials everywhere. Our drift-aware test is built for exactly this.

What this script measures (step 1: the history map)
  For every region in every session, and for each lag k = 1..K, is the stimulus side of trial t-k encoded in
  pre-stimulus activity of trial t, CONTROLLING for
     - the other lags' stimulus sides and the Bayes-optimal block prior (of the label's own sequence), and
     - the mouse's own choices and feedback on the last K trials (removed from neurons and labels)?
  Nulls: pseudo-sessions (stimulus sequences regenerated by the task's own generator), so the null is exact.
  The same quantity is also computed the standard way (per-neuron OLS t-tests, Fisher-combined) to show
  how slow drift creates false long memory.

    python3 part3/history_map.py sim              simulation checks (no data needed)
    python3 part3/history_map.py run --limit 3    quick test on real data
    python3 part3/history_map.py run              all sessions (resumable)
    python3 part3/history_map.py report           maps and tables
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
for p in (ROOT, ROOT / "next", ROOT / "driftaware" / "src"):
    sys.path.insert(0, str(p))

K = 6              # lags tested
N_NULL = 100
MIN_UNITS = 5
WINDOW = "prior_a"  # -600 to -100 ms before stimulus onset: the inter-trial "memory" period


def lags(v, k):
    T = len(v)
    out = np.zeros((T, k))
    for j in range(1, k + 1):
        out[j:, j - 1] = v[:-j]
    return out


def own_matrix(side, prior):
    """(T, K+1): stimulus side at lags 1..K (centered) and the Bayes prior (centered)."""
    s = np.nan_to_num(np.asarray(side, float) - 0.5)
    return np.column_stack([lags(s, K), np.asarray(prior, float) - 0.5])


def behaviour_history(choice, feedback):
    """(T, 2K): the mouse's own choices and feedback on the last K trials (centered). The choice x feedback
    interaction is NOT included: it equals the stimulus side, which is the variable under test."""
    c = np.where(np.asarray(choice) >= 0, np.asarray(choice, float) - 0.5, 0.0)
    f = np.asarray(feedback, float) / 2.0
    return np.hstack([lags(c, K), lags(f, K)])


# ------------------------------------------------------------------------------------------- the test
def lag_tests(X, H, owns, v, pmax=10, k_shared=1, smooth=50):
    """X: (Tfull, N) counts. H: (Tfull, q) real behaviour history (removed from neurons and labels).
    owns: (M+1, Tfull, K+1) each label sequence's own [side lags 1..K, prior]; index 0 = real.
    For each lag k the label is owns[:, :, k-1] and its controls are the other columns of the SAME sequence.
    Returns dict with p (K,), effect (K,) = S_real / mean(S_null), p_naive (K,)."""
    from scipy.signal import lfilter
    from scipy.stats import chi2, t as tdist
    from driftaware.core import _slow_components, ar_bic
    Xv = X[v].astype(float)
    Xv = Xv[:, Xv.std(0) > 0]
    O = owns[:, v, :]                                                   # (M, T, K+1)
    Hv = H[v]
    M, T, Q = O.shape
    Z = (Xv - Xv.mean(0)) / Xv.std(0)
    U = _slow_components(Xv, k_shared, smooth)
    proj = lambda A2: A2 - U @ (U.T @ A2)
    Zc = proj(Z)
    Hc = proj(Hv)
    Oc = O - np.einsum("tu,mus->mts", U, np.einsum("tu,mts->mus", U, O))
    S = np.zeros((K, M))
    naive_chi = np.zeros(K)
    N = Zc.shape[1]
    for i in range(N):
        # ---- drift-aware: AR whitening of everything with this neuron's own filter
        phi = ar_bic(Zc[:, i], pmax)
        a = np.r_[1.0, -phi]; p = len(phi)
        e = lfilter(a, [1.0], Zc[:, i] - Zc[:, i].mean())[p:]
        Hf = lfilter(a, [1.0], Hc - Hc.mean(0), axis=0)[p:]
        Hf = np.column_stack([np.ones(T - p), Hf])
        Of = lfilter(a, [1.0], Oc - Oc.mean(1, keepdims=True), axis=1)[:, p:, :]     # (M, T-p, Q)
        # remove H from neuron and from every label column
        bH = np.linalg.lstsq(Hf, e, rcond=None)[0]; e = e - Hf @ bH
        Pm = np.linalg.pinv(Hf)                                                       # (q+1, T-p)
        Of = Of - np.einsum("tq,mqs->mts", Hf, np.einsum("qt,mts->mqs", Pm, Of))
        e = (e - e.mean()) / (e.std() + 1e-12)
        for k in range(K):
            ctrl = [j for j in range(Q) if j != k]
            C = Of[:, :, ctrl]                                                        # (M, T-p, Q-1)
            g = Of[:, :, k]                                                           # (M, T-p)
            CtC = np.einsum("mts,mtu->msu", C, C) + 1e-9 * np.eye(len(ctrl))
            Ctg = np.einsum("mts,mt->ms", C, g)
            r = g - np.einsum("mts,ms->mt", C, np.linalg.solve(CtC, Ctg[..., None])[..., 0])
            r = r - r.mean(1, keepdims=True)
            r = r / (np.linalg.norm(r, axis=1, keepdims=True) + 1e-12)
            S[k] += (r @ e) ** 2 / len(e)
        # ---- naive: OLS of the raw neuron on [1, H, real own controls, real label], t-test, Fisher across neurons
        y = Z[:, i]
        for k in range(K):
            D = np.column_stack([np.ones(T), Hv, O[0][:, [j for j in range(Q) if j != k]], O[0][:, k]])
            b, res, rk, _ = np.linalg.lstsq(D, y, rcond=None)
            dof = T - rk
            resid = y - D @ b
            s2 = resid @ resid / max(dof, 1)
            cov = s2 * np.linalg.pinv(D.T @ D)
            tval = b[-1] / np.sqrt(max(cov[-1, -1], 1e-300))
            pv = 2 * tdist.sf(abs(tval), dof)
            naive_chi[k] += -2 * np.log(max(pv, 1e-300))
    p = (1 + (S[:, 1:] >= S[:, [0]]).sum(1)) / M
    eff = S[:, 0] / (S[:, 1:].mean(1) + 1e-12)
    p_naive = chi2.sf(naive_chi, 2 * N)
    return dict(p=p, effect=eff, p_naive=p_naive)


def pseudo_owns(Tf, n, rng):
    from gatekeeper.multiverse import pseudo_pl
    from compare_methods import bayes_prior
    out = []
    for _ in range(n):
        pl = pseudo_pl(Tf, rng)
        sd = (rng.random(Tf) >= pl).astype(float)
        out.append(own_matrix(sd, bayes_prior(sd)))
    return out


# ------------------------------------------------------------------------------------------- simulation
def sim_session(rng, T=600, N=25, mode="none", drift=0.6, beta=0.25, tau=2.5):
    from gatekeeper.multiverse import pseudo_pl
    from compare_methods import bayes_prior
    pl = pseudo_pl(T, rng)
    side = (rng.random(T) >= pl).astype(float)
    prior = bayes_prior(side)
    choice = np.where(rng.random(T) < 0.8, side, 1 - side).astype(int)
    fb = np.where(choice == side, 1.0, -1.0)
    z = np.zeros((T, N)); e = rng.standard_normal((T, N)); z[0] = e[0]
    for t in range(1, T):
        z[t] = 0.98 * z[t - 1] + np.sqrt(1 - 0.98 ** 2) * e[t]
    common = z[:, :1] * 0.6 + z * 0.8
    X = np.sqrt(drift) * common / common.std(0) + np.sqrt(1 - drift) * rng.standard_normal((T, N))
    w = rng.standard_normal(N)
    s = side - 0.5
    if mode == "last":            # thalamus-like: only the most recent side
        X = X + beta * np.outer(lags(s, 1)[:, 0], w) * 2
    elif mode == "integrator":    # brainstem-like: exponentially weighted sum of past sides
        Ls = lags(s, 10)
        kern = np.exp(-np.arange(10) / tau)
        X = X + beta * np.outer(Ls @ kern / kern.sum() * 4, w)
    elif mode == "prior":         # block prior only
        X = X + beta * np.outer((prior - prior.mean()) / prior.std(), w)
    return X, side, choice, fb, prior


def sim_check(reps=60, n_null=100, seed=0):
    from joblib import Parallel, delayed
    from compare_methods import bayes_prior

    def one(i, mode):
        rng = np.random.default_rng(seed + 1000 * i)
        X, side, choice, fb, prior = sim_session(rng, mode=mode)
        T = len(side)
        v = np.ones(T, bool); v[:90] = False
        owns = np.stack([own_matrix(side, prior)] + pseudo_owns(T, n_null, rng))
        r = lag_tests(X, behaviour_history(choice, fb), owns, v)
        return np.r_[r["p"] < .05, r["p_naive"] < .05]

    for mode in ("none", "last", "integrator", "prior"):
        R = np.array(Parallel(n_jobs=-1)(delayed(one)(i, mode) for i in range(reps)))
        new, naive = R[:, :K].mean(0), R[:, K:].mean(0)
        print(f"{mode:10s} new test, reject rate by lag 1..{K}: {np.round(new, 2)}   naive: {np.round(naive, 2)}", flush=True)


# ------------------------------------------------------------------------------------------- real data
def session_rows(path, n_null=N_NULL, seed=0):
    import compare_methods as cm
    from gatekeeper.multiverse import _sides
    from gatekeeper.mv_data import MVSession
    s = MVSession(path)
    v = cm.mask_of(s)
    if v is None or v.sum() < 200:
        return []
    import zlib
    rng = np.random.default_rng(seed + zlib.crc32(s.sid.encode()) % 100000)
    Tf = len(s.contrast)
    side = _sides(s)
    owns = np.stack([own_matrix(side, cm.bayes_prior(side))] + pseudo_owns(Tf, n_null, rng))
    H = behaviour_history(s.choice, s.feedback)
    rows = []
    for r in s.regions:
        X = s.X(r, WINDOW)
        if X is None:
            continue
        keep = X[v].std(0) > 0
        if keep.sum() < MIN_UNITS:
            continue
        out = lag_tests(X[:, keep], H, owns, v)
        row = dict(sid=s.sid, subject=s.subject, split=s.split, region=r, n_units=int(keep.sum()), n_trials=int(v.sum()))
        for k in range(K):
            row[f"p_lag{k + 1}"] = out["p"][k]
            row[f"eff_lag{k + 1}"] = out["effect"][k]
            row[f"pnaive_lag{k + 1}"] = out["p_naive"][k]
        rows.append(row)
    return rows


def run(cache, out_dir, limit, jobs, split):
    import pandas as pd
    from joblib import Parallel, delayed
    from gatekeeper.mv_data import MVSession
    out = Path(out_dir) / "sessions"
    out.mkdir(parents=True, exist_ok=True)
    paths = sorted(Path(cache).expanduser().glob("*.npz"))
    if split != "all":
        paths = [p for p in paths if MVSession(p).split == split]
    paths = paths[: limit or None]
    todo = [p for p in paths if not (out / f"{p.stem}.csv").exists()]
    print(f"{len(paths)} sessions, {len(paths) - len(todo)} already done, {len(todo)} to run", flush=True)
    t0 = time.time()

    def work(p):
        try:
            rows = session_rows(p)
        except Exception as e:  # one bad session must not stop the run
            print(f"FAILED {p.stem}: {type(e).__name__}: {e}", flush=True)
            rows = []
        pd.DataFrame(rows).to_csv(out / f"{p.stem}.csv", index=False)
        return len(rows)

    for i, n in enumerate(Parallel(n_jobs=jobs, return_as="generator")(delayed(work)(p) for p in todo)):
        print(f"[{i + 1}/{len(todo)}] {n} regions  ({(time.time() - t0) / 60:.1f} min)", flush=True)


def report(out_dir):
    import pandas as pd
    from verify_numbers import region_p, sig
    sys.path.insert(0, str(HERE))
    import slowmode as sm
    files = [f for f in (Path(out_dir) / "sessions").glob("*.csv") if f.stat().st_size > 1]
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    L = [f"# Where does the mouse brain hold the recent past? ({df.sid.nunique()} sessions, {df.subject.nunique()} mice, "
         f"{df.region.nunique()} regions)\n",
         "Stimulus side of trial t-k in pre-stimulus activity of trial t, controlling other lags, the block prior, and the "
         "mouse's own last-6 choices and last-6 feedback (additively). Region rule: >= 2 sessions; Fisher; BH.\n",
         "## Regions significant at FDR 5%, by lag (new test vs standard test)\n",
         "| Lag | Session-region rejection (new) | Regions (new) | Session-region rejection (standard) | Regions (standard) |",
         "|---|---|---|---|---|"]
    sigsets = {}
    for k in range(1, K + 1):
        pr = region_p(df, f"p_lag{k}"); pn = region_p(df, f"pnaive_lag{k}")
        sigsets[k] = sig(pr)
        L.append(f"| {k} | {(df[f'p_lag{k}'] < .05).mean():.3f} | {len(sig(pr))} / {len(pr)} | "
                 f"{(df[f'pnaive_lag{k}'] < .05).mean():.3f} | {len(sig(pn))} / {len(pn)} |")
    # persistence per region: longest lag with FDR-significant encoding
    regs = sorted(set(df.region))
    div = sm.division_of(regs)
    rows = []
    for r in regs:
        ks = [k for k in range(1, K + 1) if r in sigsets[k]]
        d = df[df.region == r]
        rows.append(dict(region=r, division=div.get(r, r), sessions=d.sid.nunique(), lags_sig=",".join(map(str, ks)),
                         persistence=max(ks) if ks else 0,
                         **{f"eff{k}": d[f"eff_lag{k}"].median() for k in range(1, K + 1)}))
    t = pd.DataFrame(rows)
    t2 = t[t.sessions >= 2]
    L += ["\n## Persistence by brain division (regions with >= 2 sessions)\n",
          "| Division | Regions | Any lag significant | Lag 1 | Lag 2+ | Median persistence (significant regions) |",
          "|---|---|---|---|---|---|"]
    for dv, h in t2.groupby("division"):
        anyk = h[h.persistence > 0]
        L.append(f"| {dv} | {len(h)} | {len(anyk)} | {sum(h.lags_sig.str.contains('1'))} | "
                 f"{sum(h.persistence >= 2)} | {anyk.persistence.median() if len(anyk) else 0:.0f} |")
    L += ["\n## Regions holding history beyond the last trial (persistence >= 2)\n",
          "| Region | Division | Sessions | Significant lags | Median effect lag1..6 |", "|---|---|---|---|---|"]
    for _, r in t2[t2.persistence >= 2].sort_values(["division", "persistence"], ascending=[True, False]).iterrows():
        L.append(f"| {r.region} | {r.division} | {r.sessions} | {r.lags_sig} | "
                 + " ".join(f"{r[f'eff{k}']:.2f}" for k in range(1, K + 1)) + " |")
    text = "\n".join(L)
    (Path(out_dir) / "HISTORY_MAP.md").write_text(text + "\n")
    t.to_csv(Path(out_dir) / "history_regions.csv", index=False)
    print(text)


