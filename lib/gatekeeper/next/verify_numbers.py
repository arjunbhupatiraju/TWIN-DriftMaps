"""ONE place that recomputes every headline number from the raw result files, with ONE region rule.

REGION RULE (used everywhere in the paper from now on):
    A region enters a map for a variable if it has >= 2 sessions with that variable in the data being mapped.
    Session p-values are combined with Fisher's method; Benjamini-Hochberg is applied across the included regions.
    "Replicated" = significant at FDR 5% in BOTH groups of mice, among regions that pass the rule in both groups.
Every number is printed as k / n (n = regions that passed the rule), with the file and column it came from.

    python3 next/verify_numbers.py            -> writes results/NUMBERS_LEDGER.md
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "driftaware" / "src"))
from driftaware import bh, fisher  # noqa: E402

MIN_SESSIONS = 2


def region_p(df, col, region_col="region", session_col="sid"):
    """Fisher p per region over sessions, keeping regions with >= MIN_SESSIONS sessions."""
    g = df.dropna(subset=[col]).groupby(region_col)
    n = g[session_col].nunique()
    keep = n[n >= MIN_SESSIONS].index
    return pd.Series({r: fisher(h[col].values) for r, h in g if r in keep}, dtype=float)


def sig(p, q=0.05):
    return set(p.index[bh(p.values, q)]) if len(p) else set()


def line(label, k, n, src):
    return f"| {label} | {k} / {n} | `{src}` |"


def block(title, df, var, cols, src, groups=None, session_col="sid", uncorrected=False):
    out = [f"\n### {title}\n", "| Number | Value | Source (file, column) |", "|---|---|---|"]
    d = df[df["var"] == var]
    if d.empty:
        return out + ["| (no rows for this variable) | | |"]
    for col, name in cols.items():
        if col not in d.columns:
            continue
        rate = (d[col] < 0.05).mean()
        out.append(f"| {name}: session-region rejection rate | {rate:.3f} ({len(d)} tests) | `{src}`, `{col}` |")
        p = region_p(d, col, session_col=session_col)
        if uncorrected:
            out.append(line(f"{name}: regions p < 0.05 uncorrected", int((p < 0.05).sum()), len(p), f"{src}, {col}"))
        out.append(line(f"{name}: regions FDR 5%", len(sig(p)), len(p), f"{src}, {col}"))
        out.append(line(f"{name}: regions FDR 1%", len(sig(p, 0.01)), len(p), f"{src}, {col}"))
        if groups is not None:
            ga, gb = groups
            pa = region_p(d[ga(d)], col, session_col=session_col)
            pb = region_p(d[gb(d)], col, session_col=session_col)
            com = pa.index.intersection(pb.index)
            both = sig(pa[com]) & sig(pb[com])
            out.append(line(f"{name}: replicated in both groups of mice (FDR 5%)", len(both), len(com), f"{src}, {col}"))
    return out


def main(res=ROOT / "results"):
    res = Path(res)
    L = ["# Numbers ledger (auto-generated by next/verify_numbers.py)\n",
         f"Region rule: >= {MIN_SESSIONS} sessions per region; Fisher across sessions; BH across included regions.",
         "Every number in the paper, the summary and emails must be copied from this file.\n"]

    # 1) model_real: standard vs new, all variables, both splits
    mr = {s: res / "model_real" / f"rows_{s}.csv.gz" for s in ("explore", "confirm")}
    if all(f.exists() for f in mr.values()):
        dfs = {s: pd.read_csv(f) for s, f in mr.items()}
        for s in dfs:
            dfs[s] = dfs[s][dfs[s].get("units", "good") == "good"] if "units" in dfs[s] else dfs[s]
            dfs[s]["split"] = s
        allr = pd.concat(dfs.values())
        cols = {"p_S_pseudo": "Standard (pseudo/imposter)", "p_NEW_pseudo": "New test"}
        L.append("\n## A. All task variables (model_real run)")
        for var in ("prior", "sprior", "choice", "stim_all", "feedback", "ctl_prior", "ctl_sprior", "ctl_choice"):
            L += block(f"{var}, confirm split", dfs["confirm"], var, cols, "model_real/rows_confirm.csv.gz")
            L += block(f"{var}, all mice (replication = explore vs confirm)", allr, var, cols, "model_real/rows_*.csv.gz",
                       groups=(lambda d: d.split == "explore", lambda d: d.split == "confirm"))
    else:
        L.append("\n(model_real rows not found)")

    # 2) head-to-head
    cf = {s: res / "compare2" / f"compare_rows_{s}.csv" for s in ("explore", "confirm")}
    if all(f.exists() for f in cf.values()):
        c = pd.concat([pd.read_csv(f).assign(split=s) for s, f in cf.items()])
        cols = {"p_findling_shuf": "Decoding + shuffle null", "p_findling": "Findling 2025 (reimpl.)",
                "p_zhang": "Zhang-style smoothing", "p_plain": "Standard single-neuron", "p_new": "New test"}
        L.append("\n## B. Head-to-head (compare2 run)")
        for var in ("bprior", "ctl_bprior", "prior", "ctl_prior"):
            for s in ("explore", "confirm"):
                L += block(f"{var}, {s} split", c[c.split == s], var, cols, f"compare2/compare_rows_{s}.csv", uncorrected=True)
            L += block(f"{var}, all mice", c, var, cols, "compare2/compare_rows_*.csv", uncorrected=True,
                       groups=(lambda d: d.split == "explore", lambda d: d.split == "confirm"))
    else:
        L.append("\n(compare2 rows not found)")

    # 3) detrend
    for s in ("confirm", "explore"):
        f = res / "detrend" / f"detrend_rows_{s}.csv"
        if f.exists():
            d = pd.read_csv(f)
            cols = {"p_detrend_param": "Detrend + parametric", "p_detrend_pseudo": "Detrend + pseudo", "p_new": "New test"}
            L.append(f"\n## C. Detrending baseline ({s})")
            for var in ("bprior", "ctl_bprior", "prior", "ctl_prior"):
                L += block(f"{var}, {s}", d, var, cols, f"detrend/detrend_rows_{s}.csv")

    # 4) Steinmetz
    f = res / "steinmetz" / "steinmetz_rows.csv"
    if f.exists():
        d = pd.read_csv(f)
        mice = sorted(d.mouse.unique())
        ha, hb = set(mice[0::2]), set(mice[1::2])
        cols = {"p_naive": "Standard + shuffle", "p_plain": "Standard + imposter", "p_new": "New test"}
        L.append("\n## D. Steinmetz 2019 (replication = alternating halves of the mice)")
        for var in sorted(d["var"].unique()):
            L += block(var, d, var, cols, "steinmetz/steinmetz_rows.csv", session_col="session",
                       groups=(lambda x: x.mouse.isin(ha), lambda x: x.mouse.isin(hb)))

    out = res / "NUMBERS_LEDGER.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwritten: {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ROOT / "results")
